b = load("xai_sae.json")
if b:
    car = b.get("car_at_k", b.get("car_selected"))
    mac("XtwoFeatures", b["paired"])
    mac("XtwoCAR", f"{car:.2f}")
    mac("XtwoCARpct", f"{100*car:.0f}\\%")
    mac("XtwoUnsupportedPct", f"{100*(1-car):.0f}\\%")   # was hand-copied and went stale
    mac("XtwoControl", f"{b['car_control']:.2f}")
    mac("XtwoDelta", f"{b['delta_car']:+.2f}")
    mac("XtwoCIlo", f"{b['ci'][0]:.2f}")
    mac("XtwoCIhi", f"{b['ci'][1]:.2f}")
    mac("XtwoNAR", f"{b['nar']:.2f}")
    mac("XtwoDeltaCIlo", f"{b['delta_ci'][0]:+.2f}") if "delta_ci" in b else None
    mac("XtwoDeltaCIhi", f"{b['delta_ci'][1]:+.2f}") if "delta_ci" in b else None
    mac("XtwoArms", len(b["config"]["arms"]))
    mac("XtwoUntestable", b["untestable"])
