"""Emit LaTeX macros from the shipped result files.

Numbers drifted between the abstract, the body and the appendix three times in this project --
NAR appeared as both 0.06 and 0.08, and a "38% unsupported" survived a change of CAR from 0.62 to
0.46. Copying values by hand is what caused that. This regenerates them, so a rerun updates the
paper and a contradiction becomes impossible rather than merely unlikely.

    python3 scripts/make_macros.py ../paper/xai4science > ../paper/xai4science/results.tex

The optional argument is a directory into which generated table bodies are written, so that a
table's rows are read from the result file too rather than typed beside it.
"""
import json, sys
from pathlib import Path

M = Path(__file__).resolve().parent.parent / "mechanism"


def load(n):
    p = M / n
    return json.loads(p.read_text()) if p.exists() else None


out = ["% GENERATED by scripts/make_macros.py -- do not edit by hand.",
       "% Every number below is read from a result file; rerun the script after any experiment.", ""]


def mac(name, val):
    # TeX command names are letters only: a digit in the name silently truncates the command and
    # leaves the digit as typeset material, which in a preamble \input reads as
    # "Missing \begin{document}" -- an error that names neither the macro nor this file.
    assert name.isalpha(), f"macro name must be letters only, got {name!r}"
    out.append(f"\\newcommand{{\\{name}}}{{{val}}}")


LABEL = {"identity": "identity map (harness check)", "adjacent": "adjacent layer, same model",
         "real": "the correspondence under test", "permuted_pairs": "pairings permuted",
         "residue_shuffle": "residues permuted within protein",
         "orthogonal": "the same map, randomly rotated",
         "gaussian_matched": "covariance-matched Gaussian target",
         "donor_perm": "donor permuted at patch time", "untrained": "randomly initialised target",
         "mismatched": "fitted on disjoint text"}
SHORT = {"real": "real", "positive": "positive", "correspondence-breaking": "corr.-breaking",
         "randomised": "randomised", "degenerate": "degenerate",
         "task-confounded": "task-confounded", "consequence-test control": "test control"}


def cand_table(j, path):
    """One row per candidate, medians across configurations, written from the result file."""
    import statistics as _st
    cf = list(j["configs"].values())
    order = [v for v in ("identity", "adjacent", "real", "permuted_pairs", "residue_shuffle",
                         "orthogonal", "gaussian_matched", "mismatched", "untrained",
                         "donor_perm") if any(v in c for c in cf)]
    lines = []
    for v in order:
        rs = [c[v] for c in cf if v in c]
        med = lambda k: _st.median(r[k] for r in rs)
        au = [r["auroc_vs_real"] for r in rs if r.get("auroc_vs_real") is not None]
        g1 = sum(r["guard1"] for r in rs)
        acc = sum(r["accepted"] for r in rs)
        lines.append(
            f"{LABEL[v]} & {SHORT[rs[0]['type']]} & {med('r2'):.2f} & {med('cka'):.2f} & "
            f"{g1}/{len(rs)} & {med('causal_median'):+.2f} & "
            + (f"{_st.median(au):.3f}" if au and rs[0]["type"] != "positive" else "--")
            + f" & {acc}/{len(rs)}"
            + (r" \\" if v != order[-1] else ""))
    Path(path).write_text(
        "% GENERATED by scripts/make_macros.py -- do not edit by hand.\n" + "\n".join(lines) + "\n")


def corr_audit(j, prefix):
    """Macros shared by the two correspondence experiments (X1 language, X3 protein)."""
    import statistics as _st
    cf = j["configs"]
    mac(prefix + "Configs", len(cf))
    mac(prefix + "Triples", j["config"]["triples_per_config"])
    mac(prefix + "TriplesTotal", j["config"]["triples_per_config"] * len(cf))
    mac(prefix + "NARstructural", f"{j['nar_structural_heldout']:.2f}")
    mac(prefix + "NARboth", f"{j['nar_both']:.2f}")
    mac(prefix + "NARinsample", f"{j['nar_structural_insample_small']:.2f}")
    if "par_both" in j:
        mac(prefix + "PAR", f"{j['par_both']:.2f}")
    au = [r[v]["auroc_vs_real"] for r in cf.values() for v in r
          if v != "real" and r[v].get("auroc_vs_real") is not None
          and r[v]["type"] not in ("positive",)]
    if au:
        mac(prefix + "AUROCmin", f"{min(au):.2f}")
        mac(prefix + "AUROCmedian", f"{_st.median(au):.2f}")
    mac(prefix + "RealMedian",
        f"{_st.median(r['real']['causal_median'] for r in cf.values()):.2f}")
    mac(prefix + "RealAccepted", sum(r["real"]["accepted"] for r in cf.values()))
    # How many candidates carry the SAME CKA as the genuine correspondence, to three decimals?
    # CKA never looks at the claimed map, so a correspondence and its rotation score identically.
    same, tot = [], 0
    for r in cf.values():
        base = round(r["real"]["cka"], 3)
        n = sum(1 for v in r if v != "real" and r[v]["type"] not in ("positive", "degenerate")
                and round(r[v]["cka"], 3) == base)
        same.append(n); tot = max(tot, sum(1 for v in r if v != "real"
                                           and r[v]["type"] not in ("positive", "degenerate")))
    mac(prefix + "CKAsame", min(same))
    mac(prefix + "CKAsameOf", tot)
    mac(prefix + "CKAreal", f"{_st.median(r['real']['cka'] for r in cf.values()):.3f}")
    if len(sys.argv) > 1:
        cand_table(j, Path(sys.argv[1]) / f"{prefix.lower()}_cands.tex")


ex = load("external_dysts.json")
