# --- generated table bodies ------------------------------------------------------------------
# A hand-typed table drifts exactly as a hand-typed number does, and X2's arm table had drifted
# from its own pooled row. The rows are written from the result file instead.
if len(sys.argv) > 1 and b and "per_arm" in b:
    d = Path(sys.argv[1])

    def pretty(a):
        return a.replace("pythia", "Pythia").replace("-deduped", "").replace(" L", " L")

    lines = []
    for a, v in sorted(b["per_arm"].items()):
        lines.append(f"{pretty(a)} & {v['n']} & {v['car']:.2f} & {v['control']:.2f} & "
                     f"${v['car']-v['control']:+.2f}$ \\\\")
    lines.append("\\midrule")
    lines.append(f"pooled & \\textbf{{{b['paired']}}} & "
                 f"\\textbf{{{car:.2f}}} \\, {{\\footnotesize (CI ${b['ci'][0]:.2f}$--${b['ci'][1]:.2f}$)}} & "
                 f"\\textbf{{{b['car_control']:.2f}}} & "
                 f"$\\mathbf{{{b['delta_car']:+.2f}}}$")   # the row is closed by the caller
    (d / "x2_arms.tex").write_text(
        "% GENERATED by scripts/make_macros.py -- do not edit by hand.\n" + "\n".join(lines) + "\n")

    if "per_arm" in b and any("positive" in v for v in b["per_arm"].values()):
        pl = []
        for a, v in sorted(b["per_arm"].items()):
            if "positive" not in v:
                continue
            ws = v.get("positive_wrong_sign")
            pl.append(f"{pretty(a)} & {v.get('positive_defined', 0)} & {v['positive']:.2f} & "
                      + (f"{ws:.2f}" if ws is not None else "--") + " \\\\")
        (d / "x2_positive.tex").write_text(
            "% GENERATED by scripts/make_macros.py -- do not edit by hand.\n"
            + "\n".join(pl).rstrip("\\\\") + "\n")

_defined = [l.split("{\\")[1].split("}")[0] for l in out if l.startswith("\\newcommand")]
_dupes = sorted({n for n in _defined if _defined.count(n) > 1})
assert not _dupes, f"macro defined more than once, which LaTeX rejects: {_dupes}"

print("\n".join(out))
