    mac("dystsConstPays", sum(1 for r in ex if r["res"]["constant"]["pays"]))
    mac("dystsSlowCloses", sum(1 for r in ex if r["res"]["slow"]["closes"]))
    mac("dystsMaxPay", f"{max(r['res']['constant']['r2'] for r in ex):+.3f}")

